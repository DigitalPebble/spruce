#!/usr/bin/env bash
#
# Maps each AWS and Azure region of cloud_regions.json to the WattTime region serving its
# coordinates, as returned by WattTime's /v3/region-from-loc for the co2_aoer signal.
# Regions outside the coverage of WattTime are left out.
#
# Output columns: provider,region,watttime_region
#
# Usage:  ./fetch_watttime_regions.sh [cloud_regions.json] [output.csv]
#
# Needs the credentials of a WattTime account in WATTTIME_USERNAME and WATTTIME_PASSWORD.
# Requires: bash, curl, jq.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

API="https://api.watttime.org"
CLOUD_REGIONS="${1:-$PROJECT_ROOT/src/main/resources/cloud_regions.json}"
OUTPUT="${2:-$PROJECT_ROOT/src/main/resources/watttime/regions.csv}"

: "${WATTTIME_USERNAME:?Set WATTTIME_USERNAME and WATTTIME_PASSWORD}"
: "${WATTTIME_PASSWORD:?Set WATTTIME_USERNAME and WATTTIME_PASSWORD}"

TOKEN=$(curl -sSf -u "$WATTTIME_USERNAME:$WATTTIME_PASSWORD" "$API/login" | jq -r .token)

BODY=$(mktemp)
trap 'rm -f "$BODY" "$OUTPUT.tmp"' EXIT

mkdir -p "$(dirname "$OUTPUT")"
{
    echo "# WattTime region of each cloud region, from $API/v3/region-from-loc (signal_type co2_aoer)"
    echo "# Generated by scripts/fetch_watttime_regions.sh on $(date -u +%Y-%m-%d)"
    echo "provider,region,watttime_region"
    jq -r '{aws, azure} | to_entries[] | .key as $provider | .value.cloud_regions | to_entries[]
           | select(.value.latitude != null and .value.longitude != null)
           | [$provider, .key, .value.latitude, .value.longitude] | @tsv' "$CLOUD_REGIONS" |
    while IFS=$'\t' read -r provider region latitude longitude; do
        status=$(curl -sS -o "$BODY" -w '%{http_code}' -H "Authorization: Bearer $TOKEN" \
            "$API/v3/region-from-loc?latitude=$latitude&longitude=$longitude&signal_type=co2_aoer")
        case "$status" in
            200) echo "$provider,$region,$(jq -r .region "$BODY")" ;;
            404) ;; # outside the coverage of WattTime
            *) echo "WattTime returned HTTP $status for $provider $region" >&2; exit 1 ;;
        esac
    done
} > "$OUTPUT.tmp"
mv "$OUTPUT.tmp" "$OUTPUT"
echo "Wrote $OUTPUT"
